-- 20261026_web_analytics.sql
--
-- Penghitung trafik SISI SERVER (tanpa cookie, tanpa IP mentah).
-- Ditulis oleh `src/middleware.ts` setiap request halaman publik, dibaca lewat
-- `/api/ops/analytics` dan kartu "Trafik Web" di dashboard /ops.
--
-- Kenapa di server: script analytics di browser bisa diblokir ad blocker, jadi angkanya
-- selalu lebih kecil dari kenyataan. Request yang sampai ke server tidak bisa diblokir.
--
-- Privasi: TIDAK menyimpan IP atau user-agent. Yang disimpan hanya hash
-- `sha256(secret + hari + IP + UA)`, jadi satu orang di hari yang sama = satu visitor.
--
-- Jalankan sekali di Supabase → SQL Editor.

create table if not exists public.web_visits (
  id bigint generated by default as identity primary key,
  visited_at timestamptz not null default now(),
  -- Tanggal WIB (bukan UTC) supaya "hari ini" sama dengan dashboard ops.
  day date not null,
  path text not null,
  referrer_host text,
  country text,
  device text,
  visitor_hash text not null
);

create index if not exists web_visits_day_idx on public.web_visits (day);
create index if not exists web_visits_day_visitor_idx on public.web_visits (day, visitor_hash);
create index if not exists web_visits_day_path_idx on public.web_visits (day, path);

-- Hanya service role (API server) yang boleh baca/tulis — tanpa policy untuk client.
alter table public.web_visits enable row level security;

grant all on public.web_visits to service_role;
grant usage, select on sequence public.web_visits_id_seq to service_role;

-- Ringkasan harian: pageview + visitor unik per hari.
create or replace function public.samaqu_web_daily(p_since date, p_until date)
returns table (day date, pageviews bigint, visitors bigint)
language sql
stable
as $$
  select v.day,
         count(*)::bigint as pageviews,
         count(distinct v.visitor_hash)::bigint as visitors
  from public.web_visits v
  where v.day >= p_since and v.day <= p_until
  group by v.day
  order by v.day;
$$;

-- Total satu rentang: pageview + visitor unik (unik dihitung lintas hari, bukan dijumlah per hari).
create or replace function public.samaqu_web_range(p_since date, p_until date)
returns table (pageviews bigint, visitors bigint)
language sql
stable
as $$
  select count(*)::bigint as pageviews,
         count(distinct v.visitor_hash)::bigint as visitors
  from public.web_visits v
  where v.day >= p_since and v.day <= p_until;
$$;

-- Halaman teratas dalam rentang tanggal.
create or replace function public.samaqu_web_top_paths(p_since date, p_until date, p_limit integer default 5)
returns table (path text, pageviews bigint, visitors bigint)
language sql
stable
as $$
  select v.path,
         count(*)::bigint as pageviews,
         count(distinct v.visitor_hash)::bigint as visitors
  from public.web_visits v
  where v.day >= p_since and v.day <= p_until
  group by v.path
  order by count(*) desc
  limit greatest(1, least(coalesce(p_limit, 5), 20));
$$;

revoke all on function public.samaqu_web_daily(date, date) from public, anon, authenticated;
revoke all on function public.samaqu_web_range(date, date) from public, anon, authenticated;
revoke all on function public.samaqu_web_top_paths(date, date, integer) from public, anon, authenticated;
grant execute on function public.samaqu_web_daily(date, date) to service_role;
grant execute on function public.samaqu_web_range(date, date) to service_role;
grant execute on function public.samaqu_web_top_paths(date, date, integer) to service_role;

